import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const buildDirectory = path.resolve(".next");
const staticDirectory = path.join(buildDirectory, "static");
const publicDirectory = path.resolve("public");
const fixedAssets = [
  "/",
  "/manifest.webmanifest",
  "/finora-icon-180.png",
  "/finora-icon-192.png",
  "/finora-icon-512.png",
  "/finora-icon-maskable.png",
  "/finora-mark.svg",
];

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const filePath = path.join(directory, entry.name);
    return entry.isDirectory() ? listFiles(filePath) : [filePath];
  }));
  return files.flat();
}

const staticFiles = (await listFiles(staticDirectory))
  .map((filePath) => `/_next/static/${path.relative(staticDirectory, filePath).split(path.sep).join("/")}`);
const precacheUrls = [...new Set([...fixedAssets, ...staticFiles])].sort();
const fingerprint = createHash("sha256");

for (const url of precacheUrls) {
  if (url === "/") continue;
  const filePath = url.startsWith("/_next/static/")
    ? path.join(staticDirectory, url.slice("/_next/static/".length))
    : path.join(publicDirectory, url.slice(1));
  fingerprint.update(url);
  fingerprint.update(await readFile(filePath));
}

const cacheName = `finora-shell-${fingerprint.digest("hex").slice(0, 16)}`;
const precacheAssets = precacheUrls.filter((url) => url !== "/");
const workerSource = `/* Generated by scripts/generate-pwa-service-worker.mjs. */
const CACHE_PREFIX = "finora-shell-";
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheAssets)};

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(PRECACHE_URLS);
    try {
      const response = await fetch("/", { cache: "no-store" });
      const contentType = response.headers.get("content-type") || "";
      if (response.ok && contentType.includes("text/html")) {
        await cache.put("/", response.clone());
      }
    } catch {
      // Keep installation successful even when the shell cannot be fetched.
    }
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const cacheNames = await caches.keys();
    await Promise.all(cacheNames
      .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/manus-oauth/") || url.pathname.startsWith("/_next/data/")) return;

  if (request.mode === "navigate" && (url.pathname === "/" || url.pathname === "/index.html")) {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        const contentType = response.headers.get("content-type") || "";
        if (response.ok && !response.redirected && contentType.includes("text/html")) {
          const cache = await caches.open(CACHE_NAME);
          await cache.put("/", response.clone());
        }
        return response;
      } catch {
        const cachedPage = await caches.match("/");
        return cachedPage || new Response("O Finora está offline. Conecte-se à internet e tente novamente.", {
          status: 503,
          headers: { "Content-Type": "text/plain; charset=utf-8" },
        });
      }
    })());
    return;
  }

  if (url.pathname.startsWith("/_next/static/") || PRECACHE_URLS.includes(url.pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      const cachedAsset = await cache.match(request, { ignoreSearch: true });
      if (cachedAsset) return cachedAsset;

      const response = await fetch(request);
      if (response.ok) await cache.put(request, response.clone());
      return response;
    })());
  }
});
`;

await writeFile(path.join(publicDirectory, "sw.js"), workerSource, "utf8");
console.log(`Generated public/sw.js with ${precacheUrls.length} shell URLs (${cacheName}).`);
